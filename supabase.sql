-- KIDS · Validação de rótulos. Rode este arquivo UMA vez no Supabase: SQL Editor > New query > Run.
--
-- Desenho: o site NÃO tem a amostra de mensagens. As mensagens ficam só no banco e o navegador só
-- as recebe depois de o anotador digitar o código pessoal, e só as dele. As tabelas abaixo não
-- têm nenhuma regra de acesso para a chave pública (anon): tudo passa pelas funções entrar() e salvar().
--
-- Se existirem tabelas de versões anteriores (só dados de teste), apague antes:
--   drop table if exists public.respostas, public.itens, public.anotadores cascade;

create table if not exists public.anotadores (
  slot        int  primary key,          -- 1 .. N
  codigo_hash text not null unique       -- sha256('kids:' || código sem hífen, em maiúsculas)
);

create table if not exists public.itens (
  item            bigint generated by default as identity primary key,
  message_content text not null,
  rotulo          text not null,
  persona         text,
  anotador        int                    -- preenchido por sortear_itens()
);

create table if not exists public.respostas (
  anotador      int    not null,
  item          bigint not null,
  persona       text,
  mensagem      text,
  rotulo        text,
  -- escala Likert: 1 Discordo totalmente, 2 Discordo, 3 Nem concordo nem discordo, 4 Concordo, 5 Concordo totalmente
  resposta      smallint not null check (resposta between 1 and 5),
  atualizado_em timestamptz not null default now(),
  primary key (anotador, item)
);

-- Segurança: RLS ligado e nenhum acesso direto para a chave pública.
alter table public.anotadores enable row level security;
alter table public.itens      enable row level security;
alter table public.respostas  enable row level security;
revoke all on public.anotadores, public.itens, public.respostas from anon, authenticated;

-- Descobre o anotador pelo código. Interna: o site não pode chamar.
create or replace function public._slot(p_codigo text) returns int
language sql stable security definer set search_path = public as $$
  select slot from public.anotadores
  where codigo_hash = encode(sha256(convert_to('kids:' || upper(regexp_replace(coalesce(p_codigo, ''), '[\s-]+', '', 'g')), 'UTF8')), 'hex')
$$;

-- Entrada: devolve só os itens do anotador (já em ordem embaralhada) e as respostas que ele já deu.
-- Código inválido => null.
create or replace function public.entrar(p_codigo text) returns jsonb
language plpgsql stable security definer set search_path = public as $$
declare s int := public._slot(p_codigo);
begin
  if s is null then return null; end if;
  return jsonb_build_object(
    'slot', s,
    'itens', coalesce((
      select jsonb_agg(jsonb_build_object('item', item, 'mensagem', message_content, 'rotulo', rotulo, 'persona', persona)
                       order by md5(item::text || 'ordem'))
      from public.itens where anotador = s), '[]'::jsonb),
    'respostas', coalesce((
      select jsonb_agg(jsonb_build_object('item', item, 'resposta', resposta))
      from public.respostas where anotador = s), '[]'::jsonb));
end $$;

-- Salva respostas (lista de {item, resposta}). Só aceita itens que pertencem ao anotador do código.
create or replace function public.salvar(p_codigo text, p_respostas jsonb) returns int
language plpgsql security definer set search_path = public as $$
declare s int := public._slot(p_codigo); n int;
begin
  if s is null then raise exception 'codigo invalido' using errcode = '28000'; end if;
  with e as (
    select distinct on ((x->>'item')::bigint) (x->>'item')::bigint as item, (x->>'resposta')::smallint as resposta
    from jsonb_array_elements(p_respostas) x
    order by (x->>'item')::bigint
  ), ins as (
    insert into public.respostas (anotador, item, persona, mensagem, rotulo, resposta, atualizado_em)
    select s, i.item, i.persona, i.message_content, i.rotulo, e.resposta, now()
    from e join public.itens i on i.item = e.item and i.anotador = s
    on conflict (anotador, item) do update set resposta = excluded.resposta, atualizado_em = now()
    returning 1)
  select count(*) into n from ins;
  return n;
end $$;

-- Sorteio dos itens entre os anotadores (use depois de importar a amostra). Rode com o SQL Editor:
--   select public.sortear_itens('uma-semente-qualquer');
-- Mesma semente, mesmo sorteio. Cada anotador recebe a mesma quantidade (±1).
create or replace function public.sortear_itens(p_semente text) returns void
language sql security definer set search_path = public as $$
  with n as (select count(*)::int c from public.anotadores),
  r as (select item, row_number() over (order by md5(item::text || p_semente)) - 1 as pos from public.itens)
  update public.itens i set anotador = 1 + (r.pos % n.c)::int from r, n where r.item = i.item;
$$;

-- Permissões: o site só pode chamar entrar() e salvar().
revoke all on function public._slot(text), public.sortear_itens(text) from public, anon, authenticated;
revoke all on function public.entrar(text), public.salvar(text, jsonb) from public;
grant execute on function public.entrar(text), public.salvar(text, jsonb) to anon;
