-- KIDS · Validação de rótulos. Rode este arquivo no Supabase (SQL Editor > New query > Run). Pode rodar de novo para atualizar as funções: não apaga dados.
--
-- Desenho: o site NÃO tem a amostra de mensagens. As mensagens ficam só no banco. O anotador clica no
-- próprio nome e o navegador recebe só os itens atribuídos a ele. As tabelas não têm nenhuma regra de
-- acesso para a chave pública (anon): tudo passa pelas funções listar_anotadores(), entrar() e salvar().
--
-- Papéis:
--   * anotador comum   (validador = false): cada item da amostra vai para exatamente UM anotador comum;
--   * validador        (validador = true): cada item vai também para exatamente UM validador. Com dois
--                       validadores (Kênia e Helena) cada uma recebe metade dos itens (metades disjuntas).
--
-- Se existirem tabelas de versões anteriores (só dados de teste), apague ANTES de rodar este arquivo:
--   drop table if exists public.respostas, public.itens, public.anotadores, public.atribuicoes cascade;
--   drop function if exists public.entrar(text), public.salvar(text, jsonb), public.sortear_itens(text), public._slot(text);

create table if not exists public.anotadores (
  id        int generated by default as identity primary key,
  nome      text not null unique,
  validador boolean not null default false,
  ativo     boolean not null default true,      -- false = some da lista de botões
  meta      int check (meta >= 0)               -- cota FIXA de itens (ex.: 950); vazio = divide o restante
);
alter table public.anotadores add column if not exists meta int check (meta >= 0);

create table if not exists public.itens (
  item            bigint generated by default as identity primary key,
  message_content text not null,
  rotulo          text not null,
  persona         text,
  especial        boolean not null default false,  -- item de controle: o anotador NÃO vê; aparece só nas respostas exportadas
  unique (rotulo, message_content)               -- reimportar a amostra não duplica
);
alter table public.itens add column if not exists especial boolean not null default false;

-- Quem responde o quê (um item tem 1 anotador comum + 1 validador).
create table if not exists public.atribuicoes (
  anotador int    not null references public.anotadores(id) on delete cascade,
  item     bigint not null references public.itens(item)   on delete cascade,
  primary key (anotador, item)
);
create index if not exists atribuicoes_item_idx on public.atribuicoes (item);

create table if not exists public.respostas (
  anotador      int    not null,
  anotador_nome text,
  validador     boolean,
  item          bigint not null,
  persona       text,
  especial      boolean,
  mensagem      text,
  rotulo        text,
  -- escala Likert: 1 Discordo totalmente, 2 Discordo, 3 Nem concordo nem discordo, 4 Concordo, 5 Concordo totalmente
  resposta      smallint not null check (resposta between 1 and 5),
  atualizado_em timestamptz not null default now(),
  primary key (anotador, item)
);

alter table public.respostas add column if not exists especial boolean;

-- Segurança: RLS ligado e nenhum acesso direto para a chave pública.
alter table public.anotadores  enable row level security;
alter table public.itens       enable row level security;
alter table public.atribuicoes enable row level security;
alter table public.respostas   enable row level security;
revoke all on public.anotadores, public.itens, public.atribuicoes, public.respostas from anon, authenticated;

-- Lista os botões de nome da tela inicial.
create or replace function public.listar_anotadores() returns jsonb
language sql stable security definer set search_path = public as $$
  select coalesce(jsonb_agg(jsonb_build_object('id', id, 'nome', nome) order by lower(nome)), '[]'::jsonb)
  from public.anotadores where ativo
$$;

-- Entrada: devolve só os itens do anotador (em ordem embaralhada, fixa) e as respostas que ele já deu.
-- Anotador inexistente ou inativo => null.
create or replace function public.entrar(p_anotador int) returns jsonb
language plpgsql stable security definer set search_path = public as $$
declare a public.anotadores;
begin
  select * into a from public.anotadores where id = p_anotador and ativo;
  if not found then return null; end if;
  return jsonb_build_object(
    'anotador', jsonb_build_object('id', a.id, 'nome', a.nome),
    'itens', coalesce((
      select jsonb_agg(jsonb_build_object('item', i.item, 'mensagem', i.message_content, 'rotulo', i.rotulo, 'persona', i.persona)
                       order by md5(i.item::text || 'ordem'))
      from public.atribuicoes t join public.itens i on i.item = t.item
      where t.anotador = a.id), '[]'::jsonb),
    'respostas', coalesce((
      select jsonb_agg(jsonb_build_object('item', item, 'resposta', resposta))
      from public.respostas where anotador = a.id), '[]'::jsonb));
end $$;

-- Salva respostas (lista de {item, resposta}). Só aceita itens atribuídos ao anotador.
create or replace function public.salvar(p_anotador int, p_respostas jsonb) returns int
language plpgsql security definer set search_path = public as $$
declare a public.anotadores; n int;
begin
  select * into a from public.anotadores where id = p_anotador and ativo;
  if not found then raise exception 'anotador invalido' using errcode = '28000'; end if;
  with e as (
    select distinct on ((x->>'item')::bigint) (x->>'item')::bigint as item, (x->>'resposta')::smallint as resposta
    from jsonb_array_elements(p_respostas) x
    order by (x->>'item')::bigint
  ), ins as (
    insert into public.respostas (anotador, anotador_nome, validador, item, persona, especial, mensagem, rotulo, resposta, atualizado_em)
    select a.id, a.nome, a.validador, i.item, i.persona, i.especial, i.message_content, i.rotulo, e.resposta, now()
    from e
    join public.atribuicoes t on t.item = e.item and t.anotador = a.id
    join public.itens i on i.item = e.item
    on conflict (anotador, item) do update set resposta = excluded.resposta, atualizado_em = now()
    returning 1)
  select count(*) into n from ins;
  return n;
end $$;

-- Distribui os itens ainda SEM responsável. Rode no SQL Editor depois de importar itens ou cadastrar anotadores:
--   select public.sortear_itens('uma-semente-qualquer');
-- * Só mexe em itens que ainda não têm anotador comum / validador; atribuições existentes não mudam.
-- * Cotas: anotador com `meta` recebe exatamente essa quantidade (ex.: 950); os demais anotadores do mesmo
--   papel dividem o RESTANTE em partes iguais (±1). Validadores sem meta dividem o total: com dois, metades.
-- * Os itens especiais são distribuídos primeiro, proporcionalmente às cotas, e cada pessoa recebe
--   tudo embaralhado (a ordem na tela é sorteada por pessoa em entrar()).
-- * Mesma semente + mesmo estado do banco = mesmo sorteio.
-- * Entrou gente nova depois de já haver atribuições? Use  select public.sortear_itens('semente', true);
--   Isso solta os itens ainda NÃO respondidos dos anotadores comuns (respostas e atribuições dos
--   validadores nunca são tocadas) e redistribui respeitando as cotas.
create or replace function public.sortear_itens(p_semente text, p_redistribuir boolean default false) returns jsonb
language plpgsql security definer set search_path = public as $$
declare v boolean; r record; escolhido int; novos int := 0; n_itens int;
begin
  select count(*) into n_itens from public.itens;
  if p_redistribuir then
    delete from public.atribuicoes t
    using public.anotadores a
    where a.id = t.anotador and not a.validador
      and not exists (select 1 from public.respostas x where x.anotador = t.anotador and x.item = t.item);
  end if;

  foreach v in array array[false, true] loop
    if not exists (select 1 from public.anotadores where ativo and validador = v) then
      if v = false then raise exception 'cadastre ao menos um anotador comum ativo'; end if;
      continue;   -- sem validadores ativos: nada a fazer
    end if;
    for r in
      select i.item from public.itens i
      where not exists (select 1 from public.atribuicoes t join public.anotadores a on a.id = t.anotador
                        where t.item = i.item and a.validador = v)
      order by i.especial desc, md5(i.item::text || p_semente)
    loop
      with cand as (
        select an.id, an.meta, (select count(*) from public.atribuicoes t where t.anotador = an.id) as c
        from public.anotadores an where an.ativo and an.validador = v),
      tot as (select coalesce(sum(meta), 0) as sm, greatest(count(*) filter (where meta is null), 1) as nf from cand),
      sc as (
        select c.id, c.c,
          case when c.meta is not null then c.meta
               else greatest(0, (n_itens - tot.sm) / tot.nf)
                    + case when row_number() over (partition by (c.meta is null) order by c.id)
                                <= greatest(0, n_itens - tot.sm) % tot.nf then 1 else 0 end
          end as cota
        from cand c cross join tot)
      select sc.id into escolhido from sc
      order by (sc.c >= sc.cota), sc.c::numeric / greatest(sc.cota, 1), sc.id
      limit 1;
      insert into public.atribuicoes (anotador, item) values (escolhido, r.item);
      novos := novos + 1;
    end loop;
  end loop;
  return public.progresso() || jsonb_build_object('atribuicoes_novas', novos);
end $$;

-- Painel rápido (SQL Editor):  select public.progresso();
create or replace function public.progresso() returns jsonb
language sql stable security definer set search_path = public as $$
  select jsonb_build_object('anotadores', coalesce(jsonb_agg(x order by x->>'nome'), '[]'::jsonb))
  from (
    select jsonb_build_object(
      'nome', a.nome, 'validador', a.validador, 'ativo', a.ativo, 'meta', a.meta,
      'atribuidos', (select count(*) from public.atribuicoes t where t.anotador = a.id),
      'especiais', (select count(*) from public.atribuicoes t join public.itens i on i.item = t.item where t.anotador = a.id and i.especial),
      'respondidos', (select count(*) from public.respostas r where r.anotador = a.id)) as x
    from public.anotadores a) q
$$;

-- Permissões: o site só pode chamar listar_anotadores(), entrar() e salvar().
revoke all on function public.sortear_itens(text, boolean), public.progresso() from public, anon, authenticated;
revoke all on function public.listar_anotadores(), public.entrar(int), public.salvar(int, jsonb) from public;
grant execute on function public.listar_anotadores(), public.entrar(int), public.salvar(int, jsonb) to anon;
