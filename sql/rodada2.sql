-- KIDS · RODADA 2: nova amostra, anotada por Helena e Daniel, em PARES.
-- Cada mensagem é respondida pelas duas pessoas (uma como 1ª leitura, a outra como 2ª leitura).
--
-- Tudo da rodada 2 vive em tabelas e funções NOVAS, com o sufixo _r2. Nada da rodada 1 é alterado:
-- itens, anotadores, atribuicoes e respostas (e as funções entrar/salvar/...) continuam como estão.
--
-- O site abre a rodada 2 com  ?rodada=2  no endereço (a rodada 1 continua no endereço normal).
-- Rode este arquivo UMA vez no SQL Editor; é idempotente (pode rodar de novo sem apagar dados).

-- 1. Tabelas -----------------------------------------------------------------------------------------
create table if not exists public.anotadores_r2 (
  id    int generated by default as identity primary key,
  nome  text not null unique,
  ativo boolean not null default true
);

create table if not exists public.itens_r2 (
  item            bigint generated by default as identity primary key,
  message_content text not null,
  rotulo          text not null,
  persona         text,
  especial        boolean not null default false,     -- reservado (mesmo formato da rodada 1); a nova amostra não tem controles
  unique (rotulo, message_content)
);

create table if not exists public.atribuicoes_r2 (
  anotador     int    not null references public.anotadores_r2(id) on delete cascade,
  item         bigint not null references public.itens_r2(item)    on delete cascade,
  leitura      smallint not null check (leitura in (1, 2)),         -- 1 = 1ª leitura, 2 = 2ª leitura
  lote         text,
  atribuido_em timestamptz not null default now(),
  primary key (anotador, item)                                      -- a mesma pessoa não responde o item duas vezes
);
create unique index if not exists atribuicoes_r2_item_leitura_uq on public.atribuicoes_r2 (item, leitura);  -- 1 só de cada por item

create table if not exists public.respostas_r2 (
  anotador      int    not null,
  anotador_nome text,
  item          bigint not null,
  leitura       smallint,
  persona       text,
  especial      boolean,
  mensagem      text,
  rotulo        text,
  -- escala Likert: 1 Discordo totalmente, 2 Discordo parcialmente, 3 Nem concordo nem discordo, 4 Concordo parcialmente, 5 Concordo totalmente
  resposta      smallint not null check (resposta between 1 and 5),
  atualizado_em timestamptz not null default now(),
  primary key (anotador, item)
);

alter table public.anotadores_r2  enable row level security;
alter table public.itens_r2       enable row level security;
alter table public.atribuicoes_r2 enable row level security;
alter table public.respostas_r2   enable row level security;
revoke all on public.anotadores_r2, public.itens_r2, public.atribuicoes_r2, public.respostas_r2 from anon, authenticated;

