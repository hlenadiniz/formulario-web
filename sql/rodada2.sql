insert into public.anotadores_r2 (nome) values ('Daniel'), ('Helena') on conflict (nome) do nothing;

-- 3. Funções chamadas pelo site (rodada 2) -----------------------------------------------------------
create or replace function public.listar_anotadores_r2() returns jsonb
language sql stable security definer set search_path = public as $$
  select coalesce(jsonb_agg(jsonb_build_object('id', id, 'nome', nome) order by lower(nome)), '[]'::jsonb)
  from public.anotadores_r2 where ativo
$$;

create or replace function public.entrar_r2(p_anotador int) returns jsonb
language plpgsql stable security definer set search_path = public as $$
declare a public.anotadores_r2;
begin
  select * into a from public.anotadores_r2 where id = p_anotador and ativo;
  if not found then return null; end if;
  return jsonb_build_object(
    'anotador', jsonb_build_object('id', a.id, 'nome', a.nome),
    'itens', coalesce((
      select jsonb_agg(jsonb_build_object('item', i.item, 'mensagem', i.message_content, 'rotulo', i.rotulo, 'persona', i.persona)
                       order by md5(i.item::text || 'ordem'))
      from public.atribuicoes_r2 t join public.itens_r2 i on i.item = t.item
      where t.anotador = a.id), '[]'::jsonb),
    'respostas', coalesce((
      select jsonb_agg(jsonb_build_object('item', item, 'resposta', resposta))
      from public.respostas_r2 where anotador = a.id), '[]'::jsonb));
end $$;

create or replace function public.salvar_r2(p_anotador int, p_respostas jsonb) returns int
language plpgsql security definer set search_path = public as $$
declare a public.anotadores_r2; n int;
begin
  select * into a from public.anotadores_r2 where id = p_anotador and ativo;
  if not found then raise exception 'anotador invalido' using errcode = '28000'; end if;
  with e as (
    select distinct on ((x->>'item')::bigint) (x->>'item')::bigint as item, (x->>'resposta')::smallint as resposta
    from jsonb_array_elements(p_respostas) x
    order by (x->>'item')::bigint
  ), ins as (
    insert into public.respostas_r2 (anotador, anotador_nome, item, leitura, persona, especial, mensagem, rotulo, resposta, atualizado_em)
    select a.id, a.nome, i.item, t.leitura, i.persona, i.especial, i.message_content, i.rotulo, e.resposta, now()
    from e
    join public.atribuicoes_r2 t on t.item = e.item and t.anotador = a.id
    join public.itens_r2 i on i.item = e.item
    on conflict (anotador, item) do update set resposta = excluded.resposta, atualizado_em = now()
    returning 1)
  select count(*) into n from ins;
  return n;
end $$;

-- 4. Distribuição: cada item vai para as DUAS pessoas ------------------------------------------------
-- Uma é a 1ª leitura e a outra a 2ª, alternando para ficar equilibrado (metade cada).
-- Só completa itens ainda sem atribuição; rodar de novo não muda o que já existe.
--   select public.sortear_itens_r2('rodada2');
create or replace function public.sortear_itens_r2(p_semente text) returns jsonb
language plpgsql security definer set search_path = public as $$
declare it record; ids int[]; primeiro int; segundo int; c1 bigint; c2 bigint; novos int := 0;
begin
  select array_agg(id order by id) into ids from public.anotadores_r2 where ativo;
  if coalesce(array_length(ids, 1), 0) <> 2 then
    raise exception 'a rodada 2 precisa de exatamente 2 anotadores ativos (hoje: %)', coalesce(array_length(ids, 1), 0);
  end if;

  for it in
    select i.item from public.itens_r2 i
    where not exists (select 1 from public.atribuicoes_r2 t where t.item = i.item)
    order by md5(i.item::text || p_semente)
  loop
    -- 1ª leitura: quem tem menos itens como 1ª leitura até agora
    select count(*) into c1 from public.atribuicoes_r2 where anotador = ids[1] and leitura = 1;
    select count(*) into c2 from public.atribuicoes_r2 where anotador = ids[2] and leitura = 1;
    if c1 <= c2 then primeiro := ids[1]; segundo := ids[2]; else primeiro := ids[2]; segundo := ids[1]; end if;
    insert into public.atribuicoes_r2 (anotador, item, leitura, lote) values (primeiro, it.item, 1, p_semente), (segundo, it.item, 2, p_semente);
    novos := novos + 1;
  end loop;
  return public.progresso_r2() || jsonb_build_object('itens_novos_distribuidos', novos);
end $$;

-- Painel:  select public.progresso_r2();
create or replace function public.progresso_r2() returns jsonb
language sql stable security definer set search_path = public as $$
  select jsonb_build_object(
    'total_itens', (select count(*) from public.itens_r2),
    'anotadores', coalesce(jsonb_agg(x order by x->>'nome'), '[]'::jsonb))
  from (
    select jsonb_build_object(
      'nome', a.nome, 'ativo', a.ativo,
      'atribuidos',  (select count(*) from public.atribuicoes_r2 t where t.anotador = a.id),
      'como_1a_leitura', (select count(*) from public.atribuicoes_r2 t where t.anotador = a.id and t.leitura = 1),
      'como_2a_leitura', (select count(*) from public.atribuicoes_r2 t where t.anotador = a.id and t.leitura = 2),
      'respondidos', (select count(*) from public.respostas_r2 r where r.anotador = a.id),
      'pendentes',   (select count(*) from public.atribuicoes_r2 t where t.anotador = a.id
                      and not exists (select 1 from public.respostas_r2 r where r.anotador = t.anotador and r.item = t.item))
    ) as x
    from public.anotadores_r2 a) q
$$;

-- 5. Permissões: o site só chama listar_anotadores_r2(), entrar_r2() e salvar_r2() -------------------
revoke all on function public.sortear_itens_r2(text), public.progresso_r2() from public, anon, authenticated;
revoke all on function public.listar_anotadores_r2(), public.entrar_r2(int), public.salvar_r2(int, jsonb) from public;
grant execute on function public.listar_anotadores_r2(), public.entrar_r2(int), public.salvar_r2(int, jsonb) to anon;

-- 6. Para baixar: UMA linha por mensagem, com as duas respostas lado a lado --------------------------
create or replace view public.respostas_pares_r2 with (security_invoker = true) as
select i.item, i.rotulo, i.message_content as mensagem, i.especial,
       r1.anotador_nome as anotador_1, r1.resposta as resposta_1,
       r2.anotador_nome as anotador_2, r2.resposta as resposta_2,
       abs(r1.resposta - r2.resposta) as diferenca
from public.itens_r2 i
left join public.respostas_r2 r1 on r1.item = i.item and r1.leitura = 1
left join public.respostas_r2 r2 on r2.item = i.item and r2.leitura = 2;
revoke all on public.respostas_pares_r2 from anon, authenticated;

